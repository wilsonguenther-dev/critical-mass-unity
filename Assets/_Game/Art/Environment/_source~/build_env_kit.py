"""Build the Skybreak Basin environment kit from scratch: env_kit.blend + one FBX per piece + manifest.

    /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup \
        --python "Assets/_Game/Art/Environment/_source~/build_env_kit.py"

Outputs (paths relative to this folder):
    env_kit.blend                       every piece, laid out in a lineup (source of truth is THIS script)
    ../<piece>.fbx                      one FBX per piece (Assets/_Game/Art/Environment/), the only files Unity imports
    manifest.json, MANIFEST.md          every piece: size in cells, pivot, triangle count, bible element
Exit code 0 on success; SystemExit with a message on any failure.
"""
import json
import os
import sys

import bpy

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from env_art import kit2  # noqa: E402
from env_art import pieces  # noqa: E402,F401  (v1 module; kit2 reuses its ruin/cloud builders)

OUT_FBX = os.path.dirname(HERE)          # Assets/_Game/Art/Environment
BLEND = os.path.join(HERE, "env_kit.blend")

# Same recipe as cm_art/export.py on art/warrior-blender (meshes only here).
FBX_OPTS = dict(
    use_selection=True, object_types={"MESH"}, use_mesh_modifiers=False, apply_unit_scale=True,
    apply_scale_options="FBX_SCALE_ALL", global_scale=1.0, axis_forward="-Z", axis_up="Y",
    bake_space_transform=True, mesh_smooth_type="FACE", use_tspace=False, colors_type="SRGB",
    prioritize_active_color=True, add_leaf_bones=False, bake_anim=False, use_custom_props=False,
    path_mode="AUTO", embed_textures=False,
)


def tris(ob):
    return sum(len(p.vertices) - 2 for p in ob.data.polygons)


def unity_bounds(ob):
    """Local bounds in Unity axes (unity = (-bx, bz, -by))."""
    vs = [v.co for v in ob.data.vertices]
    ux = [-v.x for v in vs]
    uy = [v.z for v in vs]
    uz = [-v.y for v in vs]
    return [round(min(ux), 4), round(min(uy), 4), round(min(uz), 4)], [round(max(ux), 4), round(max(uy), 4), round(max(uz), 4)]


def main():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scn = bpy.context.scene
    kit = bpy.data.collections.new("Kit")
    scn.collection.children.link(kit)
    known = set(bpy.ops.export_scene.fbx.get_rna_type().properties.keys())
    missing = [k for k in FBX_OPTS if k not in known]
    if missing:
        raise SystemExit(f"FBX exporter lacks options {missing}; Blender version drift?")

    rows = []
    for nm in kit2.RETIRED + ["env_" + n for n in ()]:
        stale = os.path.join(OUT_FBX, nm + ".fbx")
        if os.path.exists(stale):
            os.remove(stale)
    for idx, spec in enumerate(kit2.PIECES):
        ob = kit2.build_piece(spec, kit)
        for mname in spec["mats"]:
            ob.data.materials.append(bpy.data.materials.get(mname) or bpy.data.materials.new(mname))
        if len(ob.data.polygons) == 0:
            raise SystemExit(f"{spec['name']}: empty mesh")
        for o in bpy.context.view_layer.objects:
            o.select_set(False)
        ob.location = (0, 0, 0)
        ob.select_set(True)
        bpy.context.view_layer.objects.active = ob
        path = os.path.join(OUT_FBX, spec["name"] + ".fbx")
        res = bpy.ops.export_scene.fbx(filepath=path, **FBX_OPTS)
        if "FINISHED" not in res:
            raise SystemExit(f"FBX export failed for {spec['name']}: {res}")
        lo, hi = unity_bounds(ob)
        rows.append(dict(piece=spec["name"], fbx=os.path.relpath(path, os.path.dirname(OUT_FBX)), cat=spec["cat"],
                         pivot=spec["pivot"], tris=tris(ob), outline_px=spec["outline_px"], materials=spec["mats"],
                         verts=len(ob.data.vertices), cull=spec["cull"],
                         bounds_unity_min=lo, bounds_unity_max=hi, covers=spec["covers"],
                         team_mask=any(abs(c.color[3] - a) < 0.05 for c in ob.data.color_attributes["Col"].data
                                       for a in (0.5, 0.75, 1.0))))
        # lineup position in the .blend (export happened at the origin)
        ob.location = (-(idx % 8) * 7.0, (idx // 8) * 7.0, 0)
        ob.select_set(False)

    with open(os.path.join(HERE, "manifest.json"), "w") as f:
        json.dump(dict(generated_by="build_env_kit.py", blender=bpy.app.version_string, unit="1 unit = 1 m = 1 cell",
                       axes="Unity (x east, y up, z = -sim z)", pieces=rows), f, indent=1)
    with open(os.path.join(HERE, "MANIFEST.md"), "w") as f:
        f.write("# Environment kit v2 manifest\n\nGenerated by `build_env_kit.py` (do not edit by hand). 1 unit = 1 m = "
                "1 cell. Bounds are local, in Unity axes. Every piece drops only downward faces, so every piece may be "
                "yawed. `Outline px` = CM/Toon inverted-hull width in 1080p pixels (constant screen width). Materials are "
                "the FBX material slots (CM_Ground = world-space ground shader; decal slots are alpha-blended).\n\n")
        f.write("| Piece | Kind | Pivot | Tris | Materials | Team mask | Outline px | Bounds min .. max (x, y, z) | Bible element |\n")
        f.write("| --- | --- | --- | ---: | --- | --- | ---: | --- | --- |\n")
        for r in rows:
            f.write(f"| `{r['piece']}` | {r['cat']} | {r['pivot']} | {r['tris']} | {', '.join(r['materials'])} | "
                    f"{'yes' if r['team_mask'] else ''} | {r['outline_px']} | {r['bounds_unity_min']} .. {r['bounds_unity_max']} | "
                    f"{r['covers']} |\n")
        f.write(f"\n{len(rows)} pieces, {sum(r['tris'] for r in rows)} triangles in total.\n")
    bpy.ops.wm.save_as_mainfile(filepath=BLEND, compress=True)
    print(f"ENV_KIT_V2_OK pieces={len(rows)} tris={sum(r['tris'] for r in rows)}")


main()
