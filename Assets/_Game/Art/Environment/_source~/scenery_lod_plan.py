"""Scenery LODs, the plain-Python half (no Blender). Run from the repo root.

  python3 -I Assets/_Game/Art/Environment/_source~/scenery_lod_plan.py plan <config.json>
      Counts every kit piece (FBX triangle parse x tools/art/world-plan.tsv placements) and writes the Blender config.
  python3 -I Assets/_Game/Art/Environment/_source~/scenery_lod_plan.py land <manifest.json>
      After build_scenery_lods.py: writes .meta files for the new FBX (a copy of the source piece's importer settings
      with a fresh deterministic GUID), adds them to Resources/World/WorldKitCatalog.asset (ordinal sort, as
      ArtCatalogBuilder.BuildWorld writes it), writes Runtime/View/Dressing/SceneryLodTable.cs and copies the manifest
      to tools/art/scenery-lods.json.
"""
import hashlib, json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fbx_tris import tris

ROOT = os.getcwd()
ART = os.path.join(ROOT, "Assets/_Game/Art")
DIRS = ["Environment", "Bases"]
BREAKABLE = ("cm_hill_breakable_", "cm_shrine_breakable_", "env_wall_breakable_", "cm_wall_segment_")


def counts():
    c = {}
    for line in open(os.path.join(ROOT, "tools/art/world-plan.tsv")):
        p = line.rstrip("\n").split("\t")
        if p[0] == "piece":
            c[p[1]] = int(p[2])
    return c


def plan(out):
    c = counts()
    pieces = []
    for d in DIRS:
        for f in sorted(os.listdir(os.path.join(ART, d))):
            if not f.endswith(".fbx") or re.search(r"_lod[12]\.fbx$", f):
                continue
            name, path = f[:-4], os.path.join(ART, d, f)
            parts = tris(path)
            t = sum(x for n, x in parts if "cm_district_" in n) if name.startswith("cm_layout_") else sum(x for _, x in parts)
            pieces.append(dict(name=name, path=path, count=c.get(name, 0), tris=t, layout=name.startswith("cm_layout_"),
                               breakable=name.startswith(BREAKABLE)))
    json.dump({"pieces": pieces}, open(out, "w"), indent=1)
    print(len(pieces), "pieces;", sum(p["count"] * p["tris"] for p in pieces), "placed triangles (once)")


def guid(name):
    return hashlib.md5(("critical-mass scenery lod " + name).encode()).hexdigest()


def land(manifest_path):
    m = json.load(open(manifest_path))
    new = []
    for d in DIRS:
        for f in sorted(os.listdir(os.path.join(ART, d))):
            mm = re.match(r"(.+)_lod([12])\.fbx$", f)
            if not mm:
                continue
            src_meta = os.path.join(ART, d, mm.group(1) + ".fbx.meta")
            meta = open(src_meta).read()
            meta = re.sub(r"^guid: [0-9a-f]{32}$", "guid: " + guid(f[:-4]), meta, count=1, flags=re.M)
            open(os.path.join(ART, d, f + ".meta"), "w").write(meta)
            new.append((f[:-4], guid(f[:-4])))
    # catalog
    cat_path = os.path.join(ROOT, "Assets/_Game/Resources/World/WorldKitCatalog.asset")
    txt = open(cat_path).read()
    head, rest = txt.split("  Names:\n", 1)
    names_blk, models_blk = rest.split("  Models:\n", 1)
    names = [l[4:] for l in names_blk.splitlines() if l.startswith("  - ")]
    models = [l[4:] for l in models_blk.splitlines() if l.startswith("  - ")]
    tail = "\n".join(l for l in models_blk.splitlines() if not l.startswith("  - "))
    pairs = {n: mo for n, mo in zip(names, models) if not re.search(r"_lod[12]$", n)}
    for n, g in new:
        pairs[n] = "{fileID: 919132149155446097, guid: %s, type: 3}" % g
    keys = sorted(pairs, key=lambda s: s.encode())
    out = head + "  Names:\n" + "".join("  - %s\n" % k for k in keys) + "  Models:\n" + "".join("  - %s\n" % pairs[k] for k in keys)
    out += tail + ("\n" if tail and not tail.endswith("\n") else "")
    open(cat_path, "w").write(out)
    # table
    rows = []
    for name in sorted(m["pieces"], key=lambda s: s.encode()):
        r = m["pieces"][name]
        dims = r["dims"]
        rows.append('            { "%s", new SceneryLodRow(%d, %d, %d, %s, %sf, %sf) },' % (
            name, r["tris0"], r["lod1"] or 0, r["lod2"] or 0, "true" if r["far_cull"] else "false",
            repr(round(max(dims[0], dims[1]), 3)), repr(round(dims[2], 3))))
    cs = TEMPLATE.replace("%ROWS%", "\n".join(rows))
    open(os.path.join(ROOT, "Assets/_Game/Runtime/View/Dressing/SceneryLodTable.cs"), "w").write(cs)
    tbl_meta = os.path.join(ROOT, "Assets/_Game/Runtime/View/Dressing/SceneryLodTable.cs.meta")
    if not os.path.exists(tbl_meta):
        open(tbl_meta, "w").write(CS_META % guid("SceneryLodTable.cs"))
    json.dump(m, open(os.path.join(ROOT, "tools/art/scenery-lods.json"), "w"), indent=1, sort_keys=True)
    print("landed", len(new), "lod files;", len(rows), "table rows")


CS_META = "fileFormatVersion: 2\nguid: %s\n"

TEMPLATE = """// <auto-generated> by Assets/_Game/Art/Environment/_source~/scenery_lod_plan.py land (scenery LODs, 2026-11-12).
// Do not edit by hand: rebuild the LOD files and re-run the script. tools/art/scenery-lods.json is the full manifest.
using System.Collections.Generic;

namespace CriticalMass.Runtime.View.Dressing
{
    /// <summary>One kit piece's levels: triangles of LOD0 / LOD1 / LOD2 (0 = no such file), whether the far level is
    /// culled (tiny on screen), the footprint (largest horizontal size) and height in metres.</summary>
    public readonly struct SceneryLodRow
    {
        public readonly int Tris0, Tris1, Tris2;
        public readonly bool FarCull;
        public readonly float Footprint, Height;

        public SceneryLodRow(int tris0, int tris1, int tris2, bool farCull, float footprint, float height)
        {
            Tris0 = tris0;
            Tris1 = tris1;
            Tris2 = tris2;
            FarCull = farCull;
            Footprint = footprint;
            Height = height;
        }
    }

    public static class SceneryLodTable
    {
        public static readonly Dictionary<string, SceneryLodRow> Rows = new Dictionary<string, SceneryLodRow>
        {
%ROWS%
        };
    }
}
"""

if __name__ == "__main__":
    {"plan": plan, "land": land}[sys.argv[1]](sys.argv[2])
